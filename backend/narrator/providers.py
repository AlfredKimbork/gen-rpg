import json
import os

from google import genai
from google.genai import errors as genai_errors
from pydantic import TypeAdapter
from pydantic import ValidationError as PydanticValidationError

from narrator.prompts import DIALOGUE_PROMPT, INTERPRETER_PROMPT, NARRATOR_PROMPT
from narrator.schemas import AIActionResponse, GameAction

action_adapter = TypeAdapter(GameAction)


class MockAIProvider:
    def interpret(
        self,
        message: str,
        context: dict,
    ):
        text = message.lower()

        if "attack" in text:
            npcs = context.get("npcs", [])

            if not npcs:
                raise ValueError("No NPCs available to attack.")

            return action_adapter.validate_python(
                {
                    "type": "attack",
                    "target_slug": npcs[0].slug,
                    "weapon_slug": "rusty_sword",
                }
            )
        if "move" in text or "go to" in text:
            connections = context.get("connections", [])

            if not connections:
                raise ValueError("No connections available to move to.")

            return action_adapter.validate_python(
                {
                    "type": "move",
                    "destination_slug": connections[0].slug,
                }
            )

        if "talk" in text or "say" in text or "ask" in text:
            npcs = context.get("npcs", [])

            if not npcs:
                raise ValueError("No NPCs available to talk to.")

            return action_adapter.validate_python(
                {
                    "type": "talk",
                    "target_slug": npcs[0]["slug"],
                    "message": message,
                }
            )

        return action_adapter.validate_python(
            {
                "type": "inspect",
            }
        )

    def generate_dialogue(self, context: dict) -> str:
        return "I'm not sure what to tell you."

    def narrate(self, context: dict) -> str:
        result = context["action"]["mechanical_result"]

        return f"The action is resolved. Result: {result['type']}."


class AIProviderError(Exception):
    pass


class GeminiAIProvider:
    def __init__(self, *, client=None, model=None):
        self.client = client or genai.Client()
        self.model = model or os.getenv(
            "AI_MODEL",
            "gemini-3.5-flash-lite",
        )

    def interpret(self, message: str, context: dict):
        prompt = (
            "Current game context:\n"
            f"{json.dumps(context, ensure_ascii=False)}\n\n"
            "Player's actions:\n"
            f"{message}"
        )

        try:
            response = self.client.models.generate_content(
                model=self.model,
                contents=prompt,
                config=genai.types.GenerateContentConfig(
                    system_instruction=INTERPRETER_PROMPT,
                    response_mime_type="application/json",
                    response_schema=AIActionResponse,
                    temperature=0.1,
                ),
            )

            if response.parsed is not None:
                action = AIActionResponse.model_validate(response.parsed)
            elif response.text:
                action = AIActionResponse.model_validate_json(response.text)
            else:
                raise AIProviderError("No response from AI provider.")

            return action.to_game_action()
        except (genai_errors.APIError, PydanticValidationError, ValueError) as exc:
            raise AIProviderError(f"Failed to interpret message: {exc}") from exc

    def generate_dialogue(self, context: dict) -> str:
        prompt = json.dumps(context, ensure_ascii=False)

        try:
            response = self.client.models.generate_content(
                model=self.model,
                contents=prompt,
                config=genai.types.GenerateContentConfig(
                    system_instruction=DIALOGUE_PROMPT,
                    temperature=0.7,
                    max_output_tokens=250,
                ),
            )

            dialouge = (response.text or "").strip()

            if not dialouge:
                raise AIProviderError("No dialouge generated by AI provider.")

            return dialouge

        except genai_errors.APIError as exc:
            raise AIProviderError(f"Failed to generate dialouge: {exc}") from exc

    def narrate(self, context: dict):
        prompt = (
            "Narrate the following verified game event.\n\n"
            f"{json.dumps(context, ensure_ascii=False)}"
        )

        try:
            response = self.client.models.generate_content(
                model=self.model,
                contents=prompt,
                config=genai.types.GenerateContentConfig(
                    system_instruction=NARRATOR_PROMPT,
                    temperature=0.7,
                    max_output_tokens=1500,
                ),
            )

            narration = (response.text or "").strip()

            if not narration:
                raise AIProviderError("No narration generated by AI provider.")

            return narration
        except genai_errors.APIError as exc:
            raise AIProviderError(f"Failed to generate narration: {exc}") from exc
